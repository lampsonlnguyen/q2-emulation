import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const src = await readFile(new URL('../web/runtime/hardware.js', import.meta.url),'utf8');
const {frameRGBA,encodeEvents,keyEvents,touchEvents,wheelReports,FRAME_BYTES,WIDTH} = await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const raw = new Uint8Array(FRAME_BYTES);
raw.set([1,2,3,4],0);
raw.set([10,20,30,40],FRAME_BYTES-4);
const rgba=frameRGBA(raw);
assert.deepEqual([...rgba.slice(319*WIDTH*4,319*WIDTH*4+4)],[3,2,1,255]);
assert.deepEqual([...rgba.slice(374*4,374*4+4)],[30,20,10,255]);
assert.deepEqual([...frameRGBA(raw,true).slice(0,4)],[0,0,0,255]);
const key=encodeEvents(keyEvents('centre',true),1234);
assert.equal(key.length,32);
assert.equal(new DataView(key.buffer).getUint16(10,true),116);
assert.equal(new DataView(key.buffer).getInt32(12,true),1);
assert.deepEqual(touchEvents(374,319,'down'),[[3,0,0],[3,1,374],[3,24,1]]);
assert.deepEqual(touchEvents(0,0,'up'),[[3,24,0]]);
const wheel=wheelReports(1,100);
assert.equal(wheel.position,58);
assert.deepEqual(wheel.reports.at(-1),[[3,24,0]]);
console.log('Q2 hardware codec checks passed');
